import { z } from "zod"
import { APPARATUS_KINDS } from "./apparatus"
import { FORCE_DIRECTIONS } from "./incline"

/**
 * The validated drawing-action protocol.
 *
 * This is the only language the AI tutor (or the dev test harness) is
 * allowed to speak to the whiteboard in: a flat JSON array of actions,
 * each one validated by a strict Zod schema before anything touches the
 * engine or tldraw. There is no code-execution path here - every action
 * is data, not a script.
 */

// ─── Shared primitives ──────────────────────────────────────────────────

/** Half-extent of the addressable canvas, in tldraw page-space units. */
export const COORDINATE_LIMIT = 100_000
export const DIMENSION_MIN = 1
export const DIMENSION_LIMIT = 50_000
export const MAX_POLYLINE_POINTS = 500
export const MAX_PROGRAM_ACTIONS = 500
export const MAX_TEXT_LENGTH = 2000

export const coordinateSchema = z
  .number()
  .finite("coordinate must be a finite number")
  .min(-COORDINATE_LIMIT, `coordinate must be >= ${-COORDINATE_LIMIT}`)
  .max(COORDINATE_LIMIT, `coordinate must be <= ${COORDINATE_LIMIT}`)

export const dimensionSchema = z
  .number()
  .finite("dimension must be a finite number")
  .min(DIMENSION_MIN, `dimension must be >= ${DIMENSION_MIN}`)
  .max(DIMENSION_LIMIT, `dimension must be <= ${DIMENSION_LIMIT}`)

/** Degrees, anticlockwise as in maths: 30 tilts a box up a slope rising to the right at 30°. */
export const rotationSchema = z.number().finite().min(-360).max(360)

export const pointSchema = z.strictObject({
  x: coordinateSchema,
  y: coordinateSchema,
})
export type Point = z.infer<typeof pointSchema>

/**
 * Stable object identifier, supplied by the caller (not generated by
 * tldraw). Constrained to a safe charset because the engine derives the
 * real tldraw shape id directly from it.
 */
export const objectIdSchema = z
  .string()
  .min(1, "id must not be empty")
  .max(128, "id must be at most 128 characters")
  .regex(/^[A-Za-z0-9_-]+$/, "id may only contain letters, numbers, '_' and '-'")

export const colorSchema = z.enum([
  "black",
  "grey",
  "light-violet",
  "violet",
  "blue",
  "light-blue",
  "yellow",
  "orange",
  "green",
  "light-green",
  "light-red",
  "red",
  "white",
])
export type DrawingColor = z.infer<typeof colorSchema>

export const fillStyleSchema = z.enum(["none", "semi", "solid", "pattern", "fill", "lined-fill"])
export const dashStyleSchema = z.enum(["draw", "solid", "dashed", "dotted", "none"])
export const sizeStyleSchema = z.enum(["s", "m", "l", "xl"])
export const arrowheadStyleSchema = z.enum([
  "none",
  "arrow",
  "triangle",
  "square",
  "dot",
  "pipe",
  "diamond",
  "inverted",
  "bar",
])

export const geoShapeKindSchema = z.enum([
  "rectangle",
  "ellipse",
  "triangle",
  "diamond",
  "pentagon",
  "hexagon",
  "octagon",
  "star",
  "rhombus",
  "rhombus-2",
  "oval",
  "trapezoid",
  "x-box",
  "check-box",
  "cloud",
  "heart",
  "arrow-up",
  "arrow-down",
  "arrow-left",
  "arrow-right",
])

export const regionSchema = z.strictObject({
  x: coordinateSchema,
  y: coordinateSchema,
  w: dimensionSchema,
  h: dimensionSchema,
})
export type Region = z.infer<typeof regionSchema>

const textSchema = z.string().min(1, "text must not be empty").max(MAX_TEXT_LENGTH)

const polylinePointsSchema = z
  .array(pointSchema)
  .min(2, "at least 2 points are required")
  .max(MAX_POLYLINE_POINTS, `at most ${MAX_POLYLINE_POINTS} points are allowed`)

const polygonPointsSchema = z
  .array(pointSchema)
  .min(3, "a polygon needs at least 3 points")
  .max(MAX_POLYLINE_POINTS, `at most ${MAX_POLYLINE_POINTS} points are allowed`)

// ─── Actions ─────────────────────────────────────────────────────────────

export const createShapeActionSchema = z.strictObject({
  type: z.literal("create_shape"),
  id: objectIdSchema,
  shape: geoShapeKindSchema,
  x: coordinateSchema,
  y: coordinateSchema,
  w: dimensionSchema,
  h: dimensionSchema,
  color: colorSchema.optional(),
  fill: fillStyleSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
  label: textSchema.optional(),
  /** Turns the shape about its centre; x, y, w, h describe it before turning. */
  rotation: rotationSchema.optional(),
})

export const createFreehandPathActionSchema = z.strictObject({
  type: z.literal("create_freehand_path"),
  id: objectIdSchema,
  points: polylinePointsSchema,
  color: colorSchema.optional(),
  size: sizeStyleSchema.optional(),
  closed: z.boolean().optional(),
})

export const createPolygonActionSchema = z.strictObject({
  type: z.literal("create_polygon"),
  id: objectIdSchema,
  points: polygonPointsSchema,
  color: colorSchema.optional(),
  fill: fillStyleSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
})

export const drawLineActionSchema = z.strictObject({
  type: z.literal("draw_line"),
  id: objectIdSchema,
  points: polylinePointsSchema,
  color: colorSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
})

export const drawArrowActionSchema = z
  .strictObject({
    type: z.literal("draw_arrow"),
    id: objectIdSchema,
    start: pointSchema,
    end: pointSchema,
    color: colorSchema.optional(),
    dash: dashStyleSchema.optional(),
    size: sizeStyleSchema.optional(),
    arrowheadStart: arrowheadStyleSchema.optional(),
    arrowheadEnd: arrowheadStyleSchema.optional(),
    label: textSchema.optional(),
    bend: z.number().finite().min(-1).max(1).optional(),
  })
  .refine(
    (action) => Math.hypot(action.end.x - action.start.x, action.end.y - action.start.y) >= 4,
    "an arrow needs a real span between start and end - it can't point at nothing"
  )

/**
 * A force (or any direction vector) acting on an existing object. The engine
 * computes the geometry: the arrow starts exactly on the object's outline
 * (turned with it, if it is turned) and points at `angle` - degrees,
 * anticlockwise from the positive x direction, as in maths (0 right, 90 up,
 * 180 left, 270 down). The model never has to work out trig for it.
 */
export const drawForceActionSchema = z.strictObject({
  type: z.literal("draw_force"),
  id: objectIdSchema,
  on: objectIdSchema,
  angle: z.number().finite().min(-360).max(720).optional(),
  /** A named direction instead of an angle; the slope-relative ones use the slope the object rests on. */
  direction: z.enum(FORCE_DIRECTIONS).optional(),
  length: z.number().finite().min(20).max(600).optional(),
  label: textSchema.optional(),
  color: colorSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
}).refine((a) => (a.angle === undefined) !== (a.direction === undefined), "draw_force needs exactly one of angle or direction")

/** A slope described as a question describes it: its angle and which way is downhill. */
export const drawInclineActionSchema = z.strictObject({
  type: z.literal("draw_incline"),
  id: objectIdSchema,
  /** Top-left of the slope's bounding box. */
  position: pointSchema,
  base: z.number().finite().min(120).max(1400).optional(),
  angle: z.number().finite().min(1).max(80),
  downhill: z.enum(["left", "right"]),
  /** Shown at the angle; defaults to the angle in degrees. */
  angleLabel: textSchema.optional(),
  color: colorSchema.optional(),
  label: textSchema.optional(),
})

/** A block (or any object) resting on a slope, tilted to match it. */
export const drawOnInclineActionSchema = z.strictObject({
  type: z.literal("draw_on_incline"),
  id: objectIdSchema,
  incline: objectIdSchema,
  /** How far up the slope, 0 (bottom) to 1 (top). */
  at: z.number().min(0).max(1).optional(),
  w: z.number().finite().min(10).max(400).optional(),
  h: z.number().finite().min(10).max(400).optional(),
  shape: z.enum(["rectangle", "ellipse"]).optional(),
  color: colorSchema.optional(),
  fill: fillStyleSchema.optional(),
  label: textSchema.optional(),
})

/**
 * Marks something inside the question/student-work image the model was
 * shown: a box, circle or underline around it. `box` is [ymin, xmin, ymax,
 * xmax] on a 0-1000 scale of that image (Gemini's native box format), and
 * the renderer maps it onto where the image actually sits on the board - so
 * the model never converts coordinates itself.
 */
export const markImageActionSchema = z.strictObject({
  type: z.literal("mark_image"),
  id: objectIdSchema,
  box: z.tuple([
    z.number().min(0).max(1000), z.number().min(0).max(1000),
    z.number().min(0).max(1000), z.number().min(0).max(1000),
  ]).refine(([ymin, xmin, ymax, xmax]) => ymax > ymin && xmax > xmin, "box must be [ymin, xmin, ymax, xmax] with max > min"),
  style: z.enum(["box", "circle", "underline"]).optional(),
  color: colorSchema.optional(),
  label: textSchema.optional(),
})

const imageBoxSchema = z.tuple([
  z.number().min(0).max(1000), z.number().min(0).max(1000), z.number().min(0).max(1000), z.number().min(0).max(1000),
]).refine(([ymin, xmin, ymax, xmax]) => ymax > ymin && xmax > xmin, "box must be [ymin, xmin, ymax, xmax] with max > min")

/**
 * Copies a figure out of the question image - exactly as printed - to
 * `position`, enlarged. `box` is the figure's box in that image (0-1000, as
 * mark_image). Each named part (a mass, a block, a pulley...) gets an anchor
 * with its own id on the copy, so forces, strings and labels attach to it.
 */
export const copyFigureActionSchema = z.strictObject({
  type: z.literal("copy_figure"),
  id: objectIdSchema,
  box: imageBoxSchema,
  position: pointSchema,
  width: z.number().finite().min(120).max(1400).optional(),
  parts: z.array(z.strictObject({
    id: objectIdSchema,
    box: imageBoxSchema,
    /** For a part resting on a slope in the figure: so "up_slope", "normal"... work on it. */
    slope: z.strictObject({ angle: z.number().min(1).max(89), downhill: z.enum(["left", "right"]) }).optional(),
  })).max(12).optional(),
  label: textSchema.optional(),
})

/** A pulley wheel with its support: hung from a ceiling at `centre`, or clamped at a corner of a table or the top of a slope. */
export const drawPulleyActionSchema = z.strictObject({
  type: z.literal("draw_pulley"),
  id: objectIdSchema,
  centre: pointSchema.optional(),
  at: z.strictObject({ object: objectIdSchema, corner: z.enum(["top_left", "top_right", "slope_top"]) }).optional(),
  radius: z.number().finite().min(10).max(120).optional(),
  label: textSchema.optional(),
}).refine((a) => (a.centre === undefined) !== (a.at === undefined), "draw_pulley needs exactly one of centre or at")

/** A mass (block or particle), hanging from one side of a pulley or placed freely. */
export const drawMassActionSchema = z.strictObject({
  type: z.literal("draw_mass"),
  id: objectIdSchema,
  hang: z.strictObject({
    pulley: objectIdSchema,
    side: z.enum(["left", "right"]),
    /** From the wheel's centre down to the top of the mass. */
    drop: z.number().finite().min(30).max(900).optional(),
  }).optional(),
  position: pointSchema.optional(),
  shape: z.enum(["block", "particle"]).optional(),
  size: z.number().finite().min(16).max(200).optional(),
  color: colorSchema.optional(),
  fill: fillStyleSchema.optional(),
  label: textSchema.optional(),
}).refine((a) => (a.hang === undefined) !== (a.position === undefined), "draw_mass needs exactly one of hang or position")

/** A string or rope joining two objects, optionally passing over a pulley - its path is computed to meet both exactly. */
export const drawStringActionSchema = z.strictObject({
  type: z.literal("draw_string"),
  id: objectIdSchema,
  from: objectIdSchema,
  to: objectIdSchema,
  over: objectIdSchema.optional(),
  color: colorSchema.optional(),
})

/**
 * Highlights printed words in the question image, exactly: the words are
 * found by OCR in the image and the highlight drawn on their real pixel
 * boxes (one per line if the phrase wraps). `box` is an optional fallback
 * (same format as mark_image) used only if the words can't be found.
 */
export const highlightTextActionSchema = z.strictObject({
  type: z.literal("highlight_text"),
  id: objectIdSchema,
  text: z.string().min(1).max(200),
  occurrence: z.number().int().min(1).max(20).optional(),
  style: z.enum(["highlight", "box", "underline", "circle"]).optional(),
  color: colorSchema.optional(),
  box: z.tuple([z.number().min(0).max(1000), z.number().min(0).max(1000), z.number().min(0).max(1000), z.number().min(0).max(1000)]).optional(),
  label: textSchema.optional(),
})

/**
 * A standard piece of lab apparatus, drawn with correct proportions from a
 * kit (see apparatus.ts) as editable board shapes. Placed by `position`
 * (top-left), or `on` top of / `inside` another object by id - e.g. a
 * beaker on the tripod's gauze, a thermometer in the beaker.
 */
export const drawApparatusActionSchema = z.strictObject({
  type: z.literal("draw_apparatus"),
  id: objectIdSchema,
  kind: z.enum(APPARATUS_KINDS),
  position: pointSchema.optional(),
  on: objectIdSchema.optional(),
  inside: objectIdSchema.optional(),
  height: z.number().finite().min(30).max(800).optional(),
  /** How full, 0-1 (vessels). */
  fill: z.number().min(0).max(1).optional(),
  liquid: colorSchema.optional(),
  color: colorSchema.optional(),
  /** Bunsen burner: draw the flame. */
  lit: z.boolean().optional(),
  label: textSchema.optional(),
}).refine((a) => [a.position, a.on, a.inside].filter((v) => v !== undefined).length === 1,
  "draw_apparatus needs exactly one of position, on or inside")

/** One line of a Desmos graph: a LaTeX equation, inequality or point, e.g. "y=x^2-4" or "(2,0)". Maths only - never code. */
export const graphExpressionSchema = z.strictObject({
  latex: z.string().min(1).max(300),
  color: colorSchema.optional(),
  /** Shown beside a point, e.g. "Vertex". */
  label: z.string().max(60).optional(),
})

export const graphBoundsSchema = z.strictObject({
  left: z.number().finite(),
  right: z.number().finite(),
  bottom: z.number().finite(),
  top: z.number().finite(),
}).refine((b) => b.right > b.left && b.top > b.bottom, "graph bounds need right > left and top > bottom")

/** A live Desmos graph placed on the board, plotted exactly from its equations. */
export const drawGraphActionSchema = z.strictObject({
  type: z.literal("draw_graph"),
  id: objectIdSchema,
  position: pointSchema,
  w: z.number().finite().min(200).max(1400).optional(),
  h: z.number().finite().min(160).max(1000).optional(),
  expressions: z.array(graphExpressionSchema).min(1).max(12),
  bounds: graphBoundsSchema.optional(),
})

/** Replaces an existing Desmos graph's equations and/or view. */
export const updateGraphActionSchema = z.strictObject({
  type: z.literal("update_graph"),
  id: objectIdSchema,
  expressions: z.array(graphExpressionSchema).min(1).max(12).optional(),
  bounds: graphBoundsSchema.optional(),
}).refine((a) => a.expressions !== undefined || a.bounds !== undefined, "update_graph must change expressions or bounds")

export const drawCurveActionSchema = z.strictObject({
  type: z.literal("draw_curve"),
  id: objectIdSchema,
  start: pointSchema,
  segments: z.array(z.strictObject({ c1: pointSchema, c2: pointSchema, end: pointSchema })).min(1).max(30),
  color: colorSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
})

export const writeTextActionSchema = z.strictObject({
  type: z.literal("write_text"),
  id: objectIdSchema,
  position: pointSchema,
  text: textSchema,
  color: colorSchema.optional(),
  size: sizeStyleSchema.optional(),
  w: dimensionSchema.optional(),
})

export const drawRepeatedCurveActionSchema = z.strictObject({
  type: z.literal("draw_repeated_curve"), id: objectIdSchema,
  start: pointSchema, end: pointSchema,
  amplitude: z.number().finite().min(2).max(500),
  cycles: z.number().int().min(2).max(20),
  profile: z.enum(["wave", "loops"]),
  color: colorSchema.optional(), size: sizeStyleSchema.optional(),
}).refine(action => Math.hypot(action.end.x - action.start.x, action.end.y - action.start.y) >= 20,
  "Repeated curves need a span of at least 20 page units")

export const writeEquationActionSchema = z.strictObject({
  type: z.literal("write_equation"),
  id: objectIdSchema,
  position: pointSchema,
  expression: textSchema,
  color: colorSchema.optional(),
  size: sizeStyleSchema.optional(),
})

export const plotFunctionActionSchema = z.strictObject({
  type: z.literal("plot_function"),
  id: objectIdSchema,
  /** A restricted, safely-parsed math expression in the variable `x`, e.g. "sin(x) * 2 + 1". */
  expression: z.string().min(1).max(200),
  /** The x domain to sample over, as [min, max] with min < max. */
  domain: z
    .tuple([coordinateSchema, coordinateSchema])
    .refine(([min, max]) => min < max, "domain min must be less than domain max"),
  samples: z.number().int().min(10).max(1000).optional(),
  position: pointSchema.optional(),
  scale: z
    .strictObject({
      x: z.number().finite().positive().max(DIMENSION_LIMIT),
      y: z.number().finite().positive().max(DIMENSION_LIMIT),
    })
    .optional(),
  color: colorSchema.optional(),
  size: sizeStyleSchema.optional(),
  showAxes: z.boolean().optional(),
})

export const moveObjectActionSchema = z.strictObject({
  type: z.literal("move_object"),
  id: objectIdSchema,
  position: pointSchema,
})

export const updatePlotActionSchema = z.strictObject({
  type: z.literal("update_plot"), id: objectIdSchema,
  expression: z.string().min(1).max(200),
  domain: plotFunctionActionSchema.shape.domain.optional(),
  scale: plotFunctionActionSchema.shape.scale,
  showAxes: z.boolean().optional(),
})

export const updateObjectPatchSchema = z.strictObject({
  color: colorSchema.optional(),
  fill: fillStyleSchema.optional(),
  dash: dashStyleSchema.optional(),
  size: sizeStyleSchema.optional(),
  text: textSchema.optional(),
  w: dimensionSchema.optional(),
  h: dimensionSchema.optional(),
  opacity: z.number().min(0).max(1).optional(),
  rotation: rotationSchema.optional(),
})

export const updateObjectActionSchema = z.strictObject({
  type: z.literal("update_object"),
  id: objectIdSchema,
  patch: updateObjectPatchSchema.refine(
    (patch) => Object.keys(patch).length > 0,
    "patch must set at least one field"
  ),
})

export const deleteObjectActionSchema = z.strictObject({
  type: z.literal("delete_object"),
  id: objectIdSchema,
})

export const highlightObjectActionSchema = z.strictObject({
  type: z.literal("highlight_object"),
  id: objectIdSchema,
  color: colorSchema.optional(),
  /** Set false to remove a previously-applied highlight. Defaults to true. */
  visible: z.boolean().optional(),
})

export const clearRegionActionSchema = z.strictObject({
  type: z.literal("clear_region"),
  region: regionSchema,
})

export const focusCameraActionSchema = z.strictObject({
  type: z.literal("focus_camera"),
  target: z.discriminatedUnion("kind", [
    z.strictObject({ kind: z.literal("bounds"), region: regionSchema }),
    z.strictObject({
      kind: z.literal("point"),
      position: pointSchema,
      zoom: z.number().finite().min(0.05).max(8).optional(),
    }),
  ]),
})

